import { readFile, writeFile } from 'node:fs/promises';
import './build-brand-assets.mjs';
const fonts = await Promise.all([400, 700].map(async weight => {
  const bytes = await readFile(new URL(`../src/assets/fonts/noto-sans-${weight}.ttf`, import.meta.url));
  return `export const font${weight} = ${JSON.stringify(`data:font/ttf;base64,${bytes.toString('base64')}`)};`;
}));
await writeFile(new URL('../src/modules/documents/fonts.generated.ts', import.meta.url), `// Generated by scripts/build-assets.mjs from licensed local TTF files.\n${fonts.join('\n')}\n`);
